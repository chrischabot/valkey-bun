import { spawnSync } from "node:child_process";
import { chmodSync, existsSync, mkdirSync } from "node:fs";
import { join } from "node:path";
import type { ServerContext } from "./server-context";

// Bun 1.3.14 serves HTTP/1.1 + HTTP/2 (TCP) AND HTTP/3 over QUIC (UDP) on the
// SAME port from a single Bun.serve when `http3: true` is set alongside `tls`
// (https://bun.com/blog/bun-v1.3.14 — "HTTP/3 (QUIC) support in Bun.serve").
// HTTP/3 is experimental in 1.3.x. The single `fetch` handler serves all three
// protocols unchanged; HTTP/1.1 and HTTP/2 responses automatically advertise
// the QUIC endpoint via `Alt-Svc` so clients can upgrade. QUIC mandates TLS:
// we use an operator-provided cert/key when configured, otherwise we generate
// a local self-signed dev cert (gitignored) on first boot.

export interface AdminHandle {
  stop: () => void;
  url: string;
}

interface TlsPaths {
  keyPath: string;
  certPath: string;
}

// Operator-provided PEMs win; otherwise a self-signed dev cert is materialized
// once under `certDir` (default `<cwd>/.certs`, gitignored). openssl is used
// because Bun ships no in-process X.509 self-signed generator.
function resolveTls(certDir: string): TlsPaths {
  const envKey = process.env.VALKEY_ADMIN_TLS_KEY;
  const envCert = process.env.VALKEY_ADMIN_TLS_CERT;
  if (envKey && envCert) return { keyPath: envKey, certPath: envCert };

  const keyPath = join(certDir, "admin-key.pem");
  const certPath = join(certDir, "admin-cert.pem");
  if (!existsSync(keyPath) || !existsSync(certPath)) {
    mkdirSync(certDir, { recursive: true });
    const res = spawnSync(
      "openssl",
      [
        "req", "-x509", "-newkey", "rsa:2048", "-nodes",
        "-keyout", keyPath, "-out", certPath,
        "-days", "3650", "-subj", "/CN=localhost",
        "-addext", "subjectAltName=DNS:localhost,IP:127.0.0.1",
      ],
      { stdio: "ignore" },
    );
    if (res.status !== 0) {
      const reason = res.error && (res.error as NodeJS.ErrnoException).code === "ENOENT"
        ? "openssl was not found on PATH"
        : `openssl exited with status ${String(res.status)}`;
      throw new Error(
        `valkey2 admin: failed to generate a self-signed TLS cert for HTTP/3 ` +
        `(QUIC requires TLS): ${reason}. Install openssl, or set ` +
        `VALKEY_ADMIN_TLS_KEY and VALKEY_ADMIN_TLS_CERT to existing PEM files.`,
      );
    }
    chmodSync(keyPath, 0o600);
  }
  // Normalize permissions on reuse too (idempotent), so a key generated by an
  // older boot under a looser umask is hardened on the next start. Only the
  // generated local dev key reaches here — operator-provided env PEMs returned
  // earlier and are left untouched (they may be read-only / externally managed).
  try {
    chmodSync(keyPath, 0o600);
  } catch {
    /* best-effort hardening; ignore if the filesystem disallows chmod */
  }
  return { keyPath, certPath };
}

function jsonInfo(ctx: ServerContext): string {
  let keys = 0;
  for (const d of ctx.store.dbs) keys += d.size();
  const mem = process.memoryUsage();
  return JSON.stringify({
    server: "valkey2",
    version: "7.4.0",
    protocol: "http/3 (quic) + http/2 + http/1.1",
    uptime_seconds: Math.floor((Date.now() - ctx.startTime) / 1000),
    connected_clients: ctx.connections.size,
    total_commands_processed: ctx.totalCommands,
    total_keys: keys,
    databases: ctx.store.dbs.length,
    rss_bytes: mem.rss,
    heap_used_bytes: mem.heapUsed,
  });
}

function metricsText(ctx: ServerContext): string {
  let keys = 0;
  for (const d of ctx.store.dbs) keys += d.size();
  const mem = process.memoryUsage();
  return [
    "# HELP valkey2_uptime_seconds Server uptime in seconds.",
    "# TYPE valkey2_uptime_seconds gauge",
    `valkey2_uptime_seconds ${Math.floor((Date.now() - ctx.startTime) / 1000)}`,
    "# HELP valkey2_connected_clients Currently connected clients.",
    "# TYPE valkey2_connected_clients gauge",
    `valkey2_connected_clients ${ctx.connections.size}`,
    "# HELP valkey2_commands_processed_total Total commands processed.",
    "# TYPE valkey2_commands_processed_total counter",
    `valkey2_commands_processed_total ${ctx.totalCommands}`,
    "# HELP valkey2_keys_total Total keys across all databases.",
    "# TYPE valkey2_keys_total gauge",
    `valkey2_keys_total ${keys}`,
    "# HELP valkey2_rss_bytes Resident set size in bytes.",
    "# TYPE valkey2_rss_bytes gauge",
    `valkey2_rss_bytes ${mem.rss}`,
    "# HELP valkey2_heap_used_bytes Heap used in bytes.",
    "# TYPE valkey2_heap_used_bytes gauge",
    `valkey2_heap_used_bytes ${mem.heapUsed}`,
    "",
  ].join("\n");
}

// `http3` is recognized by Bun 1.3.14 at runtime but not yet in the pinned
// bun-types union, so the options object is passed through a structural cast
// at the Bun.serve boundary (same pattern as the Bun.listen reusePort cast).
type BunServeLike = (options: Record<string, unknown>) => {
  stop: (closeActiveConnections?: boolean) => void;
  url: URL;
};

export function startAdminServer(
  ctx: ServerContext,
  port: number,
  opts?: { certDir?: string },
): AdminHandle {
  const certDir = opts?.certDir ?? join(process.cwd(), ".certs");
  const { keyPath, certPath } = resolveTls(certDir);

  const serve = Bun.serve as unknown as BunServeLike;
  const server = serve({
    port,
    // Experimental HTTP/3 (QUIC): binds UDP for H3 and TCP for H1.1/H2 on the
    // same port; Bun appends Alt-Svc to TCP responses for client upgrade.
    http3: true,
    tls: {
      key: Bun.file(keyPath),
      cert: Bun.file(certPath),
    },
    fetch(req: Request): Response {
      const url = new URL(req.url);
      if (req.method !== "GET") {
        return new Response("method not allowed\n", {
          status: 405,
          headers: { "content-type": "text/plain" },
        });
      }
      switch (url.pathname) {
        case "/":
        case "/health":
          return new Response("OK\n", {
            status: 200,
            headers: { "content-type": "text/plain" },
          });
        case "/info":
          return new Response(jsonInfo(ctx) + "\n", {
            status: 200,
            headers: { "content-type": "application/json" },
          });
        case "/metrics":
          return new Response(metricsText(ctx), {
            status: 200,
            headers: { "content-type": "text/plain; version=0.0.4" },
          });
        default:
          return new Response("not found\n", {
            status: 404,
            headers: { "content-type": "text/plain" },
          });
      }
    },
    error(err: Error): Response {
      console.error("[valkey2 admin] serve error:", err);
      return new Response("internal error\n", { status: 500 });
    },
  });

  return {
    stop: () => server.stop(true),
    url: server.url.toString(),
  };
}